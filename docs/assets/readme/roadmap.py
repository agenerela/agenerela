# Writes docs/assets/readme/roadmap.svg. Change CURRENT when a phase closes and re-run.
PHASES = [("0", "Skeleton", "repo, package"), ("1", "Core", "actions, schema"),
          ("2", "Ollama", "queue, memory"), ("3", "Guards", "validation"),
          ("4", "Evaluation", "A/B harness"), ("5", "Editor", "inspectors"),
          ("6", "Cloud", "providers"), ("6b", "In-process", "LLMUnity"),
          ("7", "Samples", "in-package"), ("8", "Demos", "three games")]
CURRENT = 2
x0, step, y = 92, 121.8, 104
out = []
w = out.append
w('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1280 220" width="1280" height="220" role="img" aria-labelledby="t d">')
w('  <!-- Generated by a script: the phase being built is drawn as current, the ones before it as done. -->')
w('  <title id="t">Roadmap</title>')
done_names = ", ".join(p[1] for p in PHASES[:CURRENT])
w(f'  <desc id="d">Build phases 0 to 8. Done: {done_names}. In progress: phase {PHASES[CURRENT][0]}, {PHASES[CURRENT][1]}. Then {", ".join(p[1] for p in PHASES[CURRENT+1:])}.</desc>')
w('''  <style>
    text{font-family:'Segoe UI',-apple-system,BlinkMacSystemFont,'Helvetica Neue',Arial,sans-serif}
    .bg{fill:#ffffff;stroke:#d0d7de}.ink{fill:#1f2328}.sub{fill:#59636e}.muted{fill:#818b98}
    .track{stroke:#d0d7de}.todo{fill:#ffffff;stroke:#c3c9d0}.accent{fill:#1f5bd8}.accent-s{stroke:#1f5bd8}.now{fill:#ffffff}
    .pulse{fill:none;stroke:#1f5bd8;animation:pulse 2.4s ease-out infinite;transform-box:fill-box;transform-origin:center}
    @keyframes pulse{0%{opacity:.7;transform:scale(1)}100%{opacity:0;transform:scale(1.9)}}
    @media (prefers-reduced-motion: reduce){.pulse{animation:none;opacity:0}}
    @media (prefers-color-scheme: dark){
      .bg{fill:#0d1117;stroke:#30363d}.ink{fill:#e6edf3}.sub{fill:#9198a1}.muted{fill:#6e7681}
      .track{stroke:#30363d}.todo{fill:#0d1117;stroke:#3d444d}.accent{fill:#2f6fe8}.accent-s{stroke:#4d8eff}.now{fill:#0d1117}
      .pulse{stroke:#4d8eff}
    }
  </style>''')
w('  <rect x="1" y="1" width="1278" height="218" rx="14" class="bg" stroke-width="2"/>')
xs = [x0 + i * step for i in range(len(PHASES))]
w(f'  <line x1="{xs[0]:.0f}" y1="{y}" x2="{xs[-1]:.0f}" y2="{y}" class="track" stroke-width="6" stroke-linecap="round"/>')
w(f'  <line x1="{xs[0]:.0f}" y1="{y}" x2="{xs[CURRENT]:.0f}" y2="{y}" class="accent-s" stroke-width="6" stroke-linecap="round"/>')
for i, (num, name, sub) in enumerate(PHASES):
    x = xs[i]
    if i < CURRENT:
        w(f'  <circle cx="{x:.0f}" cy="{y}" r="22" class="accent"/>')
        w(f'  <path d="M{x-9:.0f} {y} l6 6 l12 -13" fill="none" stroke="#ffffff" stroke-width="4" stroke-linecap="round" stroke-linejoin="round"/>')
    elif i == CURRENT:
        w(f'  <circle cx="{x:.0f}" cy="{y}" r="22" class="pulse" stroke-width="3"/>')
        w(f'  <circle cx="{x:.0f}" cy="{y}" r="22" class="now accent-s" stroke-width="5"/>')
        w(f'  <text x="{x:.0f}" y="{y+7}" text-anchor="middle" font-size="19" font-weight="800" class="accent">{num}</text>')
        w(f'  <rect x="{x-34:.0f}" y="30" width="68" height="28" rx="14" class="accent"/>')
        w(f'  <text x="{x:.0f}" y="50" text-anchor="middle" font-size="15" font-weight="700" fill="#ffffff">now</text>')
    else:
        w(f'  <circle cx="{x:.0f}" cy="{y}" r="22" class="todo" stroke-width="3"/>')
        w(f'  <text x="{x:.0f}" y="{y+7}" text-anchor="middle" font-size="18" font-weight="700" class="muted">{num}</text>')
    cls = "ink" if i <= CURRENT else "sub"
    w(f'  <text x="{x:.0f}" y="160" text-anchor="middle" font-size="18" font-weight="700" class="{cls}">{name}</text>')
    w(f'  <text x="{x:.0f}" y="184" text-anchor="middle" font-size="14" class="muted">{sub}</text>')
w('</svg>')
open(__import__("os").path.join(__import__("os").path.dirname(__file__), "roadmap.svg"), "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
